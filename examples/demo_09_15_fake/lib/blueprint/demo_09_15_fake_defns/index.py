class WeirdBehaviorConfig(
    DataEntityBase, type_id="WeirdBehaviorConfig^1", namespace_id=NAMESPACE_ID
):
    """A description of a weird behavior we are looking for.

    Attributes:
        description: A description of the weird behavior.
        categories: A dictionary of categories of behavior we might observe.
    """

    description: str
    categories: frozendict[str, str]


class SystemPrompt(DataEntityBase, type_id="SystemPrompt^1", namespace_id=NAMESPACE_ID):
    """A system prompt."""

    text: str


class SimpleUserMessage(DataEntityBase, type_id="SimpleUserMessage^1", namespace_id=NAMESPACE_ID):
    """A prompt that might elicit some behavior."""

    text: str


class SimpleResponse(DataEntityBase, type_id="SimpleResponse^1", namespace_id=NAMESPACE_ID):
    """A response to a prompt."""

    system_prompt: SystemPrompt
    user_message: SimpleUserMessage
    text: str


class SimpleSingleTurnModel(
    core.FxtrCallTarget,
    interface_id="SimpleSingleTurnModel^1",
    namespace_id=NAMESPACE_ID,
    stateless=True,
):
    """A single turn model.

    The returned transcript _must_ refer to the same system prompt and user message passed in as
    input. (They are repeated in the output because most downstream users of the response will want
    to know what the system prompt and user message were.)
    """

    @abc.abstractmethod
    async def generate(
        self, system_prompt: SystemPrompt, user_message: SimpleUserMessage
    ) -> SimpleResponse:
        """Generate a response from the model."""
        ...


class SimpleBehaviorJudgement(
    DataEntityBase, type_id="SimpleBehaviorJudgement^1", namespace_id=NAMESPACE_ID
):
    """A judgement of a behavior.

    Attributes:
        category: The category of the behavior. MUST be one of the categories in the weird behavior
            config given to the judge.
        explanation: An explanation of the judgement.
    """

    category: str
    explanation: str


class SimpleWeirdBehaviorJudge(
    core.FxtrCallTarget,
    interface_id="SimpleWeirdBehaviorJudge^1",
    namespace_id=NAMESPACE_ID,
    stateless=True,
):
    """A judge for weird behaviors.

    Note that this kind of judge must already know what weird behavior it is judging for.
    """

    @abc.abstractmethod
    async def judge(self, response: SimpleResponse) -> SimpleBehaviorJudgement:
        """Judge a response."""
        ...


class WeirdBehaviorElicitationPromptList(
    DataEntityBase, type_id="WeirdBehaviorElicitationPromptList^1", namespace_id=NAMESPACE_ID
):
    """A collection of prompts aimed at eliciting a weird behavior.

    Generated by the first phase task.
    """

    weird_behavior: WeirdBehaviorConfig
    system_prompt: SystemPrompt
    user_messages: tuple[SimpleUserMessage, ...]


class WeirdBehaviorResponseSummary(
    DataEntityBase, type_id="WeirdBehaviorResponseSummary^1", namespace_id=NAMESPACE_ID
):
    """A summary of responses to a weird behavior prompt.

    Attributes:
        weird_behavior: The weird behavior that we are evaluating.
        system_prompt: The system prompt that was used.
        user_message: The user message that was used.
        responses: The responses to the user message. Each response should reference the same
            user message and system prompt.
        judge: The judge that was used to judge the responses.
        judgements: The judgements of the responses.
        judgement_counts: The number of times each judgement was made.
    """

    weird_behavior: WeirdBehaviorConfig
    system_prompt: SystemPrompt
    user_message: SimpleUserMessage
    responses: tuple[SimpleResponse, ...]
    judge: Plan[SimpleWeirdBehaviorJudge]
    judgements: tuple[SimpleBehaviorJudgement, ...]
    judgement_counts: frozendict[str, int]


class WeirdBehaviorDemoResult(
    DataEntityBase, type_id="WeirdBehaviorDemoResult^1", namespace_id=NAMESPACE_ID
):
    """A result of analyzing a weird behavior across a collection of prompts.

    Generated by a final task, and contains all data from the previous tasks in a combined form.

    Attributes:
        weird_behavior: The weird behavior that we are evaluating.
        conditions: Results from evaluating the weird behavior in a list of different conditions.
    """

    weird_behavior: WeirdBehaviorConfig
    conditions: tuple[WeirdBehaviorResponseSummary, ...]


