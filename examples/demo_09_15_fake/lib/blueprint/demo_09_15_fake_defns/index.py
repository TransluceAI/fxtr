def setup_openai_weird_behavior_judge(
    weird_behavior: WeirdBehaviorConfig, model_name: str, oai_requires: str = "openai==1.108.0"
) -> PyImplPlan[SimpleWeirdBehaviorJudge]:
    """Set up a simple weird behavior judge implemented using an OpenAI model."""
    return PyImplPlan(
        interface_spec=core.spec_of(SimpleWeirdBehaviorJudge),
        requires=f"demo_09_15_fake==0.0.1\n{oai_requires}",
        constructor="demo_09_15_fake.openai_judge:SimpleBehaviorJudge_OpenAIImpl._ainit",
        kwargs=frozendict(weird_behavior=weird_behavior, model_name=model_name),
        impl_deps=frozenset({openai_api_key.handle}),
    )


def setup_judge_task(
    sample_result: Plan[StorageHandle[SimpleResponse]],
    judge: Plan[SimpleWeirdBehaviorJudge],
) -> Task[SimpleBehaviorJudgement]:
    """Set up judge task."""
    # This task pins a version of the openai package that is incompatible with the version of the
    # package used by the simple judge implementation. This isn't actually necessary here but it
    # is the kind of thing that might happen in a real world scenario, as a demonstration of how
    # fxtr can support this case.
    return Task(
        PyImplPlan(
            interface_spec=core.spec_of(TaskFunction[SimpleBehaviorJudgement]),
            requires="demo_09_15_fake==0.0.1\nopenai==1.107.3",
            constructor="demo_09_15_fake.task_judge_behavior:Task_WeirdBehaviorJudge",
            kwargs=frozendict(sample_result=sample_result, judge=judge),
            impl_deps=frozenset({sample_result, judge}),
        )
    )


# top-level builder


class Demo0915Experiment(DataEntityBase, type_id="Demo0915Experiment^1", namespace_id=NAMESPACE_ID):
    """Full experiment for the demo, including all tasks."""

    # Configuration
    weird_behavior: WeirdBehaviorConfig
    num_prompts: int
    num_samples_per_prompt: int
    investigator_model: Plan[SimpleSingleTurnModel]
    subject_model: Plan[SimpleSingleTurnModel]
    judge: Plan[SimpleWeirdBehaviorJudge]
    # Tasks (can be used to get results)
    idea_gen_task: Task[WeirdBehaviorElicitationPromptList]
    sample_tasks: tuple[tuple[Task[SimpleResponse], ...], ...]
    judge_tasks: tuple[tuple[Task[SimpleBehaviorJudgement], ...], ...]
    collect_task: Task[WeirdBehaviorDemoResult]


def build_demo_09_15(
    behavior: WeirdBehaviorConfig,
    num_prompts: int = 10,
    num_samples_per_prompt: int = 10,
    subject_model_name: str = "gpt-5-nano-2025-08-07",
    investigator_model_name: str = "gpt-5-mini-2025-08-07",
    judge_model_name: str = "gpt-5-mini-2025-08-07",
) -> Demo0915Experiment:
    """Build a demo 09 15 experiment."""
    subject_model = setup_openai_single_turn_model(subject_model_name)
    investigator_model = setup_openai_single_turn_model(investigator_model_name)
    judge = setup_openai_weird_behavior_judge(behavior, judge_model_name)
    idea_gen_task = setup_idea_generation_task(behavior, investigator_model, num_prompts)
    sample_tasks = tuple(
        setup_sample_tasks_for_prompt(
            _setup_projector(idea_gen_task.result_handle, i),
            subject_model,
            num_samples_per_prompt,
        )
        for i in range(num_prompts)
    )
    judge_tasks = tuple(
        tuple(setup_judge_task(st.result_handle, judge) for st in group) for group in sample_tasks
    )
    # this task is awkward to separate out so we just include it inline here
    # in general maybe there should be simpler ways to build this kind of thing but I guess this
    # isn't _that_ bad even by itself
    collect_task = Task(
        PyImplPlan(
            interface_spec=core.spec_of(TaskFunction[WeirdBehaviorDemoResult]),
            requires="demo_09_15_fake==0.0.1",
            constructor="demo_09_15_fake.task_collect_results:Task_CollectWeirdBehaviorResults",
            kwargs=frozendict(
                weird_behavior=behavior,
                judge=judge,
                idea_gen_handle=idea_gen_task.result_handle,
                sample_handles=tuple(
                    tuple(st.result_handle for st in group) for group in sample_tasks
                ),
                judge_handles=tuple(
                    tuple(jt.result_handle for jt in group) for group in judge_tasks
                ),
            ),
            impl_deps=frozenset(
                {
                    idea_gen_task.result_handle,
                    *(st.result_handle for group in sample_tasks for st in group),
                    *(jt.result_handle for group in judge_tasks for jt in group),
                }
            ),
        )
    )
    return Demo0915Experiment(
        weird_behavior=behavior,
        num_prompts=num_prompts,
        num_samples_per_prompt=num_samples_per_prompt,
        subject_model=subject_model,
        investigator_model=investigator_model,
        judge=judge,
        idea_gen_task=idea_gen_task,
        sample_tasks=sample_tasks,
        judge_tasks=judge_tasks,
        collect_task=collect_task,
    )
