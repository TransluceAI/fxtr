def cleanup_soon_handler(thunk: Callable[[], Awaitable[None]]) -> None:
    print("Cleanup triggered synchronously!")

    async def _go():
        print("Cleanup running")
        await thunk()
        print("Cleanup done")

    asyncio.create_task(_go())


