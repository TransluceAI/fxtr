"""The checked-in coverage tables: rendering audit rows, reading them back, and diffing."""

import collections
import json
from collections.abc import Sequence
from pathlib import Path
from typing import Any, cast

import yaml

from behaviors.types.dialect import Dialect

from .audit import DialectAudit, Row

TABLES = (
    Path(__file__).parents[2] / "src" / "behaviors" / "implementations" / "dialects" / "coverage"
)

_HEADER = """\
# Coverage of the {dialect} request schema by its codec: every path the provider's request
# schema allows, probed one at a time through decode_request -> encode_request ->
# compare_request (the passthrough reconstruction check).
#
#   verdict    ok | known_loss | unhandled | unprobed
#   fate       what the codec does with the field: modeled (the vocabulary carries it), extra
#              (kept in DialectExtras: a same-dialect subject gets it, any other does not),
#              dropped, or altered
#   treatment  how the reconstruction check compares it: exact, normalized (to a canonical
#              spelling, still compared), or ignored (invisible to the check)
#   reasons    the loss the decoder recorded, the ignore or normalization that applied, the
#              differences the check reported, or why the path could not be probed
#   below      the number of paths under this one that share its row exactly
#
# Generated by behaviors/tests/dialect_coverage; do not edit. Regenerate with
#   BEHAVIORS_UPDATE_CODEC_COVERAGE=1 pytest tests/dialect_coverage
"""


def table_path(dialect: Dialect) -> Path:
    return TABLES / f"{dialect}.yaml"


def collapse(rows: Sequence[Row]) -> list[tuple[Row, int]]:
    """The rows to list, each with how many rows beneath it it stands for: a row whose every
    descendant has the same classification lists them as a count."""
    out: list[tuple[Row, int]] = []
    index = 0
    while index < len(rows):
        row = rows[index]
        end = index + 1
        while end < len(rows) and _is_below(rows[end].path, row.path):
            end += 1
        subtree = rows[index + 1 : end]
        if subtree and all(_outcome(other) == _outcome(row) for other in subtree):
            out.append((row, len(subtree)))
            index = end
        else:
            out.append((row, 0))
            index += 1
    return out


def _is_below(path: str, ancestor: str) -> bool:
    return path.startswith(ancestor) and path[len(ancestor) : len(ancestor) + 1] in (".", "[", "<")


def _outcome(row: Row) -> tuple[object, ...]:
    return (row.verdict, row.fate, row.treatment, row.reasons)


def entry(row: Row, below: int) -> dict[str, Any]:
    out: dict[str, Any] = {"verdict": row.verdict}
    if row.fate is not None:
        out["fate"] = row.fate
    if row.treatment is not None:
        out["treatment"] = row.treatment
    if row.reasons:
        out["reasons"] = list(row.reasons)
    if below:
        out["below"] = below
    return out


def render(spec: DialectAudit, rows: Sequence[Row]) -> str:
    counts = collections.Counter(row.verdict for row in rows)
    lines = [
        _HEADER.format(dialect=spec.dialect),
        f"dialect: {spec.dialect}",
        f"schema: {json.dumps(spec.schema_source)}",
        f"paths: {len(rows)}",
        "verdicts: "
        + json.dumps(
            {v: counts[v] for v in ("ok", "known_loss", "unhandled", "unprobed") if counts[v]}
        ),
        "rows:",
    ]
    for row, below in collapse(rows):
        lines.append(f"  {json.dumps(row.path)}: {json.dumps(entry(row, below))}")
    return "\n".join(lines) + "\n"


def load(dialect: Dialect) -> dict[str, Any] | None:
    path = table_path(dialect)
    if not path.exists():
        return None
    return cast("dict[str, Any]", yaml.safe_load(path.read_text()))


def describe_changes(expected: dict[str, Any], spec: DialectAudit, rows: Sequence[Row]) -> str:
    """What differs between the checked-in table and this audit, row by row, with the witness
    of each changed or new row so the probe can be rerun by hand."""
    lines: list[str] = []
    if expected.get("schema") != spec.schema_source:
        lines.append(f"schema: {expected.get('schema')} -> {spec.schema_source}")
    by_path = {row.path: row for row in rows}
    old = cast("dict[str, dict[str, Any]]", expected.get("rows") or {})
    new = {row.path: entry(row, below) for row, below in collapse(rows)}
    for path in sorted(old.keys() | new.keys()):
        if old.get(path) == new.get(path):
            continue
        lines.append(f"{path}:")
        lines.append(f"  table: {json.dumps(old.get(path))}")
        lines.append(f"  audit: {json.dumps(new.get(path))}")
        row = by_path.get(path)
        if row is not None and row.witness is not None:
            witness = json.dumps(row.witness, sort_keys=True)
            lines.append(f"  witness ({row.pointer}): {witness}")
    return "\n".join(lines)
