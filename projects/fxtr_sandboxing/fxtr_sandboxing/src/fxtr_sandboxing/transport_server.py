"""Env-level transport connection server.

The :class:`TransportConnectionServer` owns the per-environment table of
single-use transport tokens. Each token maps to a :data:`TransportHandler` —
a sync callable that takes ownership of an incoming byte stream when the
sandbox redeems the token via the runtime-specific side channel.

Stage-3 design notes:

- **Token shape**: 32-byte hex strings (``secrets.token_hex(32)``), 256
  bits of entropy. Generated by the authorizer impl, registered here on
  the way out.
- **Single-use**: ``consume_token`` does an atomic pop. A second redemption
  raises :class:`BadTransportTokenError`. Witness-driven revocation goes
  through ``revoke_token`` which is idempotent.
- **Threading**: ``register_token`` / ``revoke_token`` run on the host's
  async loop (RPC dispatch / witness GC); ``consume_token`` is also
  invoked from the eryx callback thread. Dict mutations are guarded by a
  ``threading.Lock`` for clarity even though CPython's GIL already makes
  individual ops atomic.
- **Handler ownership**: The handler is invoked synchronously when the
  sandbox redeems a token. It takes ownership of the byte stream
  (including close) and is responsible for any async work — typical
  pattern is to ``start_soon`` on a task group of its own choosing. The
  server hands off and returns; it does not track handler lifetime. The
  underlying socket is owned by the env / runner, so when the env tears
  down the stream's other end closes naturally and any in-flight handler
  async work sees EOF / a broken stream.
- **No dispatch method**: The server doesn't drive the side-channel
  protocol itself — the eryx and container runners each catch
  :class:`BadTransportTokenError` from ``consume_token`` and surface
  failure in the way that makes sense for their transport (eryx's sync
  callback raises out; the container accept loop writes a routing-header
  error response and closes). Keeps the server's responsibilities
  narrow: registry + atomic lookup.
"""

from __future__ import annotations

import threading
from collections.abc import Callable

import aiohttp
import anyio.abc

from .proxy import (
    PassthroughHostsConfig,
    TransportRoute,
    passthrough_proxy_connection,
    proxy_connection,
)

# A handler takes ownership of the byte stream (including close) and is
# responsible for spawning any async work it needs. The server invokes the
# handler synchronously and forgets — see the module docstring.
type TransportHandler = Callable[[anyio.abc.ByteStream], None]


class BadTransportTokenError(LookupError):
    """Raised when a sandbox redeems a missing / already-consumed token."""


class TransportConnectionServer:
    """Env-level token table."""

    def __init__(self) -> None:
        self._table: dict[str, TransportHandler] = {}
        self._lock = threading.Lock()

    def register_token(self, token: str, handler: TransportHandler) -> None:
        """Insert ``token → handler`` in the table.

        Caller is responsible for token uniqueness (use
        ``secrets.token_hex(32)``); we treat collisions as a bug.
        """
        with self._lock:
            if token in self._table:
                raise ValueError(f"transport token already registered: {token!r}")
            self._table[token] = handler

    def revoke_token(self, token: str) -> None:
        """Remove ``token`` from the table; idempotent.

        No-op if the token isn't present — handles the "consumed before
        revoke" race when the witness's GC fires after the side channel
        has already popped the token.
        """
        with self._lock:
            self._table.pop(token, None)

    def consume_token(self, token: str) -> TransportHandler:
        """Atomically look up and remove ``token``.

        Raises :class:`BadTransportTokenError` if the token is missing —
        either because it was never minted or because it's already been
        consumed / revoked.
        """
        with self._lock:
            handler = self._table.pop(token, None)
        if handler is None:
            raise BadTransportTokenError(f"transport token unknown or already consumed: {token!r}")
        return handler


def make_http_route_handler(
    route: TransportRoute,
    upstream_session: aiohttp.ClientSession,
    env_tg: anyio.abc.TaskGroup,
) -> TransportHandler:
    """Build a ``TransportHandler`` that proxies HTTP via ``proxy_connection``.

    The returned sync handler captures ``env_tg`` and starts an async
    proxy task on it for each incoming connection. ``proxy_connection``
    owns the stream's close; the handler does not own the upstream
    session's lifecycle (the env-level exit stack does).
    """

    def handler(stream: anyio.abc.ByteStream) -> None:
        env_tg.start_soon(proxy_connection, stream, route, upstream_session)

    return handler


def make_passthrough_http_handler(
    config: PassthroughHostsConfig,
    upstream_session: aiohttp.ClientSession,
    env_tg: anyio.abc.TaskGroup,
) -> TransportHandler:
    """Build a ``TransportHandler`` that proxies HTTP via
    :func:`passthrough_proxy_connection`. Same lifecycle contract as
    :func:`make_http_route_handler`; the upstream session belongs to
    the env's exit stack."""

    def handler(stream: anyio.abc.ByteStream) -> None:
        env_tg.start_soon(passthrough_proxy_connection, stream, config, upstream_session)

    return handler
