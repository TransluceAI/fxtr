import abc

from frozendict import frozendict

from fxtr.impl_plans.py_impl_plan import PyImplPlan
from fxtr.object_model import collection_tracking, core
from fxtr.object_model.core import DataEntityBase, Plan, StorageHandle, Task, TaskFunction

NAMESPACE_ID = "2936aca9-f2af-48f4-a8f0-34b32632d83d"
collection_tracking.declare_collection_module(namespace_id=NAMESPACE_ID)

openai_api_key = core.declare_secret(
    secret_id="openai_api_key^1",
    env_var="OPENAI_API_KEY",
    optional=False,
    namespace_id=NAMESPACE_ID,
    doc=f"""The API key for accessing OpenAI models.""",
)


class TargetBehaviorConfig(
    DataEntityBase, type_id="TargetBehaviorConfig^1", namespace_id=NAMESPACE_ID
):
    """A description of a target behavior we are looking for.

    Attributes:
        description: A description of the target behavior.
        categories: A dictionary of categories of behavior we might observe.
    """

    description: str
    categories: frozendict[str, str]


class SystemPrompt(DataEntityBase, type_id="SystemPrompt^1", namespace_id=NAMESPACE_ID):
    """A system prompt."""

    text: str


class SimpleUserMessage(DataEntityBase, type_id="SimpleUserMessage^1", namespace_id=NAMESPACE_ID):
    """A prompt that might elicit some behavior."""

    text: str


class SimpleResponse(DataEntityBase, type_id="SimpleResponse^1", namespace_id=NAMESPACE_ID):
    """A response to a prompt."""

    system_prompt: SystemPrompt
    user_message: SimpleUserMessage
    text: str


class SimpleSingleTurnModel(
    core.FxtrCallTarget,
    interface_id="SimpleSingleTurnModel^1",
    namespace_id=NAMESPACE_ID,
    stateless=True,
):
    """A single turn model.

    The returned transcript _must_ refer to the same system prompt and user message passed in as
    input. (They are repeated in the output because most downstream users of the response will want
    to know what the system prompt and user message were.)
    """

    @abc.abstractmethod
    async def generate(
        self, system_prompt: SystemPrompt, user_message: SimpleUserMessage
    ) -> SimpleResponse:
        """Generate a response from the model."""
        ...


class SimpleBehaviorJudgement(
    DataEntityBase, type_id="SimpleBehaviorJudgement^1", namespace_id=NAMESPACE_ID
):
    """A judgement of a behavior.

    Attributes:
        category: The category of the behavior. MUST be one of the categories in the target behavior
            config given to the judge.
        explanation: An explanation of the judgement.
    """

    category: str
    explanation: str


class SimpleTargetBehaviorJudge(
    core.FxtrCallTarget,
    interface_id="SimpleTargetBehaviorJudge^1",
    namespace_id=NAMESPACE_ID,
    stateless=True,
):
    """A judge for target behaviors.

    Note that this kind of judge must already know what target behavior it is judging for.
    """

    @abc.abstractmethod
    async def judge(self, response: SimpleResponse) -> SimpleBehaviorJudgement:
        """Judge a response."""
        ...


class PromptVariation(DataEntityBase, type_id="PromptVariation^1", namespace_id=NAMESPACE_ID):
    """A variation of a prompt."""

    variant_description: str
    system_prompt: SystemPrompt
    user_message: SimpleUserMessage


class PromptVariationsSweep(
    DataEntityBase, type_id="PromptVariationsSweep^1", namespace_id=NAMESPACE_ID
):
    """A collection of prompts aimed at eliciting a target behavior.

    Generated by the first phase task.
    """

    explanation: str
    target_behavior: TargetBehaviorConfig
    variation_target: str
    variations: tuple[PromptVariation, ...]


class TargetBehaviorResponseSummary(
    DataEntityBase, type_id="TargetBehaviorResponseSummary^1", namespace_id=NAMESPACE_ID
):
    """A summary of responses to a target behavior prompt across multiple models.

    Attributes:
        target_behavior: The target behavior that we are evaluating.
        variant_description: Description of what this variant is and how it differs.
        system_prompt: The system prompt that was used.
        user_message: The user message that was used.
        responses: The responses to the user message, keyed by model name.
        judge: The judge that was used to judge the responses.
        judgements: The judgements of the responses, keyed by model name.
        judgement_counts: The number of times each judgement was made, keyed by model name.
    """

    target_behavior: TargetBehaviorConfig
    variant_description: str
    system_prompt: SystemPrompt
    user_message: SimpleUserMessage
    responses: frozendict[str, tuple[SimpleResponse, ...]]
    judge: Plan[SimpleTargetBehaviorJudge]
    judgements: frozendict[str, tuple[SimpleBehaviorJudgement, ...]]
    judgement_counts: frozendict[str, frozendict[str, int]]


class TargetBehaviorDemoResult(
    DataEntityBase, type_id="TargetBehaviorDemoResult^1", namespace_id=NAMESPACE_ID
):
    """A result of analyzing a target behavior across a collection of prompts.

    Generated by a final task, and contains all data from the previous tasks in a combined form.

    Attributes:
        target_behavior: The target behavior that we are evaluating.
        variation_target: The part of the system prompt that was varied.
        conditions: Results from evaluating the target behavior in a list of different conditions.
    """

    target_behavior: TargetBehaviorConfig
    variation_target: str
    conditions: tuple[TargetBehaviorResponseSummary, ...]


# setup initial task
def setup_variant_generation_task(
    initial_system_prompt: SystemPrompt,
    user_message: SimpleUserMessage,
    behavior: TargetBehaviorConfig,
    variation_target: str,
    investigator_model: Plan[SimpleSingleTurnModel],
    num_prompts: int = 10,
) -> Task[PromptVariationsSweep]:
    """Set up first phase task."""
    return Task(
        PyImplPlan(
            interface_spec=core.spec_of(TaskFunction[PromptVariationsSweep]),
            requires="demo_agentic_misalignment==0.0.1",
            constructor="demo_agentic_misalignment.task_generate_variations:Task_GenerateVariationsOfSystemPrompt",
            kwargs=frozendict(
                initial_system_prompt=initial_system_prompt,
                user_message=user_message,
                behavior=behavior,
                variation_target=variation_target,
                num_prompts=num_prompts,
                investigator_model=investigator_model,
            ),
            impl_deps=frozenset({investigator_model}),
        )
    )


# setup sample task


def setup_openai_single_turn_model(
    model_name: str,
) -> PyImplPlan[SimpleSingleTurnModel]:
    """Set up a simple single turn model implemented using an OpenAI model."""
    return PyImplPlan(
        interface_spec=core.spec_of(SimpleSingleTurnModel),
        requires="demo_agentic_misalignment==0.0.1",
        constructor=(
            "demo_agentic_misalignment.openai_model:SimpleSingleTurnModel_OpenAIImpl._ainit"
        ),
        kwargs=frozendict({"model_name": model_name}),
        impl_deps=frozenset({openai_api_key.handle}),
    )


def _setup_projector(
    variant_generation_result: Plan[StorageHandle[PromptVariationsSweep]],
    input_index: int,
) -> PyImplPlan[StorageHandle[PromptVariation]]:
    """Set up a projector for the prompt at the given index.

    TODO(daniel): this should probably not be a PyImplPlan, we will want this to be easier to
    configure, something like

        StorageView(variant_generation_result, lambda result: result.ideas[input_index])

    but this requires something like starlark in order to be safely serializable. or maybe we can
    interpret it by using a proxy object at definition time and storing it as an AccessPath? but
    regardless this should be a type that is built into core and has its own provider that doesn't
    require spawning a separate python worker process.
    """
    return PyImplPlan(
        interface_spec=core.spec_of(StorageHandle[PromptVariation]),
        requires="demo_agentic_misalignment==0.0.1",
        constructor="demo_agentic_misalignment.storage_projector:StorageHandle_Project",
        kwargs=frozendict(
            handle=variant_generation_result,
            access_path=(
                ("attr", "variations"),
                ("item", input_index),
            ),
        ),
        impl_deps=frozenset({variant_generation_result}),
    )


def setup_sample_tasks_for_prompt(
    prompt_handle: Plan[StorageHandle[PromptVariation]],
    model: Plan[SimpleSingleTurnModel],
    num_samples: int,
) -> tuple[Task[SimpleResponse], ...]:
    """Set up sample task."""
    sample_tasks = []
    for i in range(num_samples):
        sample_tasks.append(
            Task(
                PyImplPlan(
                    interface_spec=core.spec_of(TaskFunction[SimpleResponse]),
                    requires="demo_agentic_misalignment==0.0.1",
                    constructor=(
                        "demo_agentic_misalignment.task_sample_from_model:Task_SampleFromModel"
                    ),
                    kwargs=frozendict(prompt_handle=prompt_handle, model=model),
                    impl_deps=frozenset({prompt_handle, model}),
                ),
                tag=i,
            )
        )
    return tuple(sample_tasks)


# setup judge task


def setup_openai_target_behavior_judge(
    target_behavior: TargetBehaviorConfig, model_name: str
) -> PyImplPlan[SimpleTargetBehaviorJudge]:
    """Set up a simple target behavior judge implemented using an OpenAI model."""
    return PyImplPlan(
        interface_spec=core.spec_of(SimpleTargetBehaviorJudge),
        requires="demo_agentic_misalignment==0.0.1\nopenai==1.108.0",
        constructor="demo_agentic_misalignment.openai_judge:SimpleBehaviorJudge_OpenAIImpl._ainit",
        kwargs=frozendict(target_behavior=target_behavior, model_name=model_name),
        impl_deps=frozenset({openai_api_key.handle}),
    )


def setup_judge_task(
    sample_result: Plan[StorageHandle[SimpleResponse]],
    judge: Plan[SimpleTargetBehaviorJudge],
) -> Task[SimpleBehaviorJudgement]:
    """Set up judge task."""
    # This task pins a version of the openai package that is incompatible with the version of the
    # package used by the simple judge implementation. This isn't actually necessary here but it
    # is the kind of thing that might happen in a real world scenario, as a demonstration of how
    # fxtr can support this case.
    return Task(
        PyImplPlan(
            interface_spec=core.spec_of(TaskFunction[SimpleBehaviorJudgement]),
            requires="demo_agentic_misalignment==0.0.1\nopenai==1.107.3",
            constructor="demo_agentic_misalignment.task_judge_behavior:Task_TargetBehaviorJudge",
            kwargs=frozendict(sample_result=sample_result, judge=judge),
            impl_deps=frozenset({sample_result, judge}),
        )
    )


# top-level builder


class Demo0915Experiment(DataEntityBase, type_id="Demo0915Experiment^1", namespace_id=NAMESPACE_ID):
    """Full experiment for the demo, including all tasks."""

    # Configuration
    initial_system_prompt: SystemPrompt
    user_message: SimpleUserMessage
    target_behavior: TargetBehaviorConfig
    variation_target: str
    num_prompts: int
    num_samples_per_prompt: int
    investigator_model: Plan[SimpleSingleTurnModel]
    subject_models: frozendict[str, Plan[SimpleSingleTurnModel]]
    judge: Plan[SimpleTargetBehaviorJudge]
    # Tasks (can be used to get results)
    var_gen_task: Task[PromptVariationsSweep]
    sample_tasks: frozendict[str, tuple[tuple[Task[SimpleResponse], ...], ...]]
    judge_tasks: frozendict[str, tuple[tuple[Task[SimpleBehaviorJudgement], ...], ...]]
    collect_task: Task[TargetBehaviorDemoResult]


def build_demo_agentic_misalignment(
    initial_system_prompt: SystemPrompt,
    user_message: SimpleUserMessage,
    behavior: TargetBehaviorConfig,
    variation_target: str,
    subject_model_names: list[str],
    num_prompts: int = 10,
    num_samples_per_prompt: int = 10,
    investigator_model_name: str = "gpt-5-mini-2025-08-07",
    judge_model_name: str = "gpt-5-mini-2025-08-07",
) -> Demo0915Experiment:
    """Build a demo 09 15 experiment."""
    # Create subject models
    subject_models = {}
    for model_name in subject_model_names:
        subject_models[model_name] = setup_openai_single_turn_model(model_name)

    investigator_model = setup_openai_single_turn_model(investigator_model_name)
    judge = setup_openai_target_behavior_judge(behavior, judge_model_name)
    var_gen_task = setup_variant_generation_task(
        initial_system_prompt=initial_system_prompt,
        user_message=user_message,
        behavior=behavior,
        variation_target=variation_target,
        investigator_model=investigator_model,
        num_prompts=num_prompts,
    )
    # Create sample and judge tasks for each model and each prompt variation
    sample_tasks_by_model = {}
    judge_tasks_by_model = {}

    for model_name, subject_model in subject_models.items():
        model_sample_tasks = tuple(
            setup_sample_tasks_for_prompt(
                _setup_projector(var_gen_task.result_handle, i),
                subject_model,
                num_samples_per_prompt,
            )
            for i in range(num_prompts)
        )
        model_judge_tasks = tuple(
            tuple(setup_judge_task(st.result_handle, judge) for st in group)
            for group in model_sample_tasks
        )

        sample_tasks_by_model[model_name] = model_sample_tasks
        judge_tasks_by_model[model_name] = model_judge_tasks
    # this task is awkward to separate out so we just include it inline here
    # in general maybe there should be simpler ways to build this kind of thing but I guess this
    # isn't _that_ bad even by itself
    collect_task = Task(
        PyImplPlan(
            interface_spec=core.spec_of(TaskFunction[TargetBehaviorDemoResult]),
            requires="demo_agentic_misalignment==0.0.1",
            constructor=(
                "demo_agentic_misalignment.task_collect_results:Task_CollectTargetBehaviorResults"
            ),
            kwargs=frozendict(
                target_behavior=behavior,
                variation_target=variation_target,
                judge=judge,
                var_gen_handle=var_gen_task.result_handle,
                sample_handles=frozendict(
                    {
                        model_name: tuple(
                            tuple(st.result_handle for st in group) for group in model_tasks
                        )
                        for model_name, model_tasks in sample_tasks_by_model.items()
                    }
                ),
                judge_handles=frozendict(
                    {
                        model_name: tuple(
                            tuple(jt.result_handle for jt in group) for group in model_tasks
                        )
                        for model_name, model_tasks in judge_tasks_by_model.items()
                    }
                ),
            ),
            impl_deps=frozenset(
                {
                    var_gen_task.result_handle,
                    *(
                        st.result_handle
                        for model_tasks in sample_tasks_by_model.values()
                        for group in model_tasks
                        for st in group
                    ),
                    *(
                        jt.result_handle
                        for model_tasks in judge_tasks_by_model.values()
                        for group in model_tasks
                        for jt in group
                    ),
                }
            ),
        )
    )
    return Demo0915Experiment(
        initial_system_prompt=initial_system_prompt,
        user_message=user_message,
        target_behavior=behavior,
        variation_target=variation_target,
        num_prompts=num_prompts,
        num_samples_per_prompt=num_samples_per_prompt,
        subject_models=frozendict(subject_models),
        investigator_model=investigator_model,
        judge=judge,
        var_gen_task=var_gen_task,
        sample_tasks=frozendict(sample_tasks_by_model),
        judge_tasks=frozendict(judge_tasks_by_model),
        collect_task=collect_task,
    )
